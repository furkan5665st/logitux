use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum MouseSeries {
    Gaming,
    MxMaster,
    Office,
    Unknown,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ButtonLayoutSlot {
    pub index: u8,
    pub label: &'static str,
    pub x: f32,
    pub y: f32,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MouseProfileMeta {
    pub pid: u16,
    pub model_name: &'static str,
    pub series: MouseSeries,
    pub button_count: u8,
    pub rgb_zones: u8,
    pub is_perkey_rgb: bool,
    pub default_dpi_min: u16,
    pub default_dpi_max: u16,
    pub default_dpi_step: u16,
    pub has_onboard_profiles: bool,
    pub has_wireless_battery: bool,
}

